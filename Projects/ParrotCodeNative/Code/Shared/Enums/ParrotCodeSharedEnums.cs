namespace ParrotCode.Native
{
    /// <summary>
    /// Represents a direction relative to the device screen.
    /// </summary>
    public enum ScreenDirection
    {
        /// <summary>
        /// Towards the top of the screen.
        /// </summary>
        Up,

        /// <summary>
        /// Towards the bottom of the screen.
        /// </summary>
        Down,

        /// <summary>
        /// Towards the left side of the screen.
        /// </summary>
        Left,

        /// <summary>
        /// Towards the right side of the screen.
        /// </summary>
        Right
    }

    /// <summary>
    /// Represents a direction relative to a transform's local coordinate system.
    /// </summary>
    public enum TransformDirection
    {
        /// <summary>
        /// In the transform's forward direction.
        /// </summary>
        Forward,

        /// <summary>
        /// In the transform's backward direction.
        /// </summary>
        Backward,

        /// <summary>
        /// In the transform's left direction.
        /// </summary>
        Left,

        /// <summary>
        /// In the transform's right direction.
        /// </summary>
        Right
    }

    /// <summary>
    /// Represents the type of output generated by a Unity build target.
    /// </summary>
    public enum BuildOutput
    {
        /// <summary>
        /// The build output is a single file (for example, an APK or EXE).
        /// </summary>
        File,

        /// <summary>
        /// The build output is a directory containing multiple files (for example, a WebGL build or an iOS Xcode project).
        /// </summary>
        Folder
    }

    /// <summary>
    /// Represents the supported file extensions used by the Parrot Code framework.
    /// </summary>
    /// <remarks>
    /// This enumeration provides a strongly typed way to reference common file
    /// extensions when constructing file paths or performing file-related
    /// operations. Use the corresponding extension utility methods to convert
    /// these values into their string representations (for example, ".json").
    /// </remarks>
    public enum FileExtension
    {
        /// <summary>
        /// JavaScript Object Notation (.json) file.
        /// </summary>
        JSON,

        /// <summary>
        /// Extensible Markup Language (.xml) file.
        /// </summary>
        XML,

        /// <summary>
        /// Plain text (.txt) file.
        /// </summary>
        Text,

        /// <summary>
        /// Log (.log) file.
        /// </summary>
        Log,

        /// <summary>
        /// Markdown (.md) document.
        /// </summary>
        Markdown,

        /// <summary>
        /// Portable Network Graphics (.png) image.
        /// </summary>
        PNG,

        /// <summary>
        /// Joint Photographic Experts Group (.jpg) image.
        /// </summary>
        JPG,

        /// <summary>
        /// Joint Photographic Experts Group (.jpeg) image.
        /// </summary>
        JPEG,

        /// <summary>
        /// Portable Document Format (.pdf) document.
        /// </summary>
        PDF,

        /// <summary>
        /// Android application package (.apk).
        /// </summary>
        APK,

        /// <summary>
        /// Executable application (.exe).
        /// </summary>
        Executable
    }
}
